/*
 * pointer_demo.c — ポインタの基本を学ぶためのサンプル
 *
 * ビルド: make pointer
 * 実行:   make pointer-run
 */
#include <stdio.h>

/* 値を2倍にして呼び出し元の変数を書き換える（ポインタ経由） */
static void double_value(int *p)
{
    /*
     * フロー: main から int 変数のアドレスが渡される
     * → *p で「そのアドレスにある int」を読み書きできる
     */
    if (p == NULL) {
        return;
    }
    *p = *p * 2;
}

int main(void)
{
    printf("=== ポインタ学習デモ ===\n\n");

    /* ----------------------------------------------------------
     * 1. 変数とポインタの関係（& と *）
     * ---------------------------------------------------------- */
    int x = 10;

    /*
     * p は「int を指すポインタ」
     * &x は変数 x のメモリ上のアドレス（番地）
     */
    int *p = &x;

    printf("[1] 変数とアドレス\n");
    printf("    x の値     : %d\n", x);
    printf("    x のアドレス: %p  (&x)\n", (void *)&x);
    printf("    p が保持する: %p  (x の番地そのもの)\n", (void *)p);
    printf("    *p で読むと : %d  (p が指す先の値)\n\n", *p);

    /* ----------------------------------------------------------
     * 2. ポインタ経由で元の変数を書き換える
     * ---------------------------------------------------------- */
    printf("[2] 間接参照で x を変更\n");
    *p = 99; /* p が指す先（= x）に 99 を書き込む */
    printf("    *p = 99 のあと、x = %d\n\n", x);

    /* ----------------------------------------------------------
     * 3. 関数にポインタを渡す（call by address）
     * ---------------------------------------------------------- */
    int n = 5;
    printf("[3] 関数にアドレスを渡して書き換え\n");
    printf("    呼び出し前: n = %d\n", n);
    double_value(&n); /* n の住所を渡す → 関数内の変更が n に反映される */
    printf("    呼び出し後: n = %d\n\n", n);

    /* ----------------------------------------------------------
     * 4. 配列とポインタ（配列名は先頭要素へのポインタ）
     * ---------------------------------------------------------- */
    int arr[4] = {10, 20, 30, 40};
    int *cursor = arr; /* arr と &arr[0] は同じアドレス */

    printf("[4] 配列をポインタで走査\n");
    printf("    arr の先頭アドレス: %p\n", (void *)arr);

  /*
   * フロー: cursor が arr[0] を指す
   *        → *cursor で値取得、cursor++ で次の int へ（4バイト進む想定）
   */
    for (int i = 0; i < 4; i++) {
        printf("    [%d] アドレス=%p  値=%d\n", i, (void *)cursor, *cursor);
        cursor++;
    }
    printf("\n");

    /* 添字記法 arr[i] は *(arr + i) と同じ意味 */
    printf("    arr[2] と *(arr+2) は同じ: %d, %d\n\n", arr[2], *(arr + 2));

    /* ----------------------------------------------------------
     * 5. ポインタのポインタ（二重間接）
     * ---------------------------------------------------------- */
    int value = 42;
    int *ptr = &value;
    int **pptr = &ptr; /* ptr のアドレスを保持 */

    printf("[5] 二重ポインタ\n");
    printf("    value = %d\n", value);
    printf("    *ptr  = %d  (ptr が指す value)\n", *ptr);
    printf("    **pptr = %d  (pptr → ptr → value)\n\n", **pptr);

    /* ----------------------------------------------------------
     * 6. スタック上のローカル変数のアドレス（学習用の注意）
     * ---------------------------------------------------------- */
    int stack_var = 100;
    int *stack_ptr = &stack_var;

    printf("[6] ローカル変数（スタック）の例\n");
    printf("    stack_var のアドレス: %p\n", (void *)&stack_var);
    printf("    stack_ptr 経由の値  : %d\n", *stack_ptr);
    printf("    ※ アドレスは実行のたびに変わることがある\n");
    printf("    ※ 解放済みメモリを指すポインタ（ダングリング）は使わない\n");

    return 0;
}
